import json

def main():
    # Словник з 10 записів: {"Прізвище": ["Ім'я", "По батькові", рік народження]}
    data = {
        "Сніжко": ["Іван", "Олександрович", 2004],
        "Шевченко": ["Тарас", "Григорович", 1814],
        "Франко": ["Іван", "Якович", 1856],
        "Українка": ["Леся", "Петрівна", 1871],
        "Коцюбинський": ["Михайло", "Михайлович", 1864],
        "Костенко": ["Ліна", "Василівна", 1930],
        "Стус": ["Василь", "Семенович", 1938],
        "Сковорода": ["Григорій", "Савич", 1722],
        "Нечуй-Левицький": ["Іван", "Семенович", 1838],
        "Рильський": ["Максим", "Тадейович", 1895]
    }

    json_filename = "students_data.json"

    # 1. Запис у JSON з ensure_ascii=False (збереження кирилиці як літер)
    with open(json_filename, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=4)
    print(f"Дані успішно збережено у файл '{json_filename}' (кодування UTF-8).\n")

    # 2. Зчитування з JSON файлу та вивід у консоль
    with open(json_filename, "r", encoding="utf-8") as f:
        loaded_data = json.load(f)

    print("--- Прочитані дані з JSON файлу ---")
    for surname, info in loaded_data.items():
        print(f"{surname}: {info[0]} {info[1]}, {info[2]} р.н.")

if __name__ == "__main__":
    main()